    DATEDIFF_BIG(MILLISECOND, @INICIO, @FIN) AS TIEMPO_MS,
    DATEDIFF_BIG(MILLISECOND, @INICIO, @FIN) / 1000.0 AS TIEMPO_SEGUNDOS;
