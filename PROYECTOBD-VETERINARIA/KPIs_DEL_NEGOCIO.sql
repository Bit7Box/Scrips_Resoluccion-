-- INGRESOS PROMEDIO POR CLIENTE ATENDIDO
-- Equivalente conceptual: [Ingresos Totales] / [Clientes Atendidos]
SELECT
    CAST(SUM(F.MONTO_ATENCION) AS DECIMAL(18,2)) AS INGRESOS_TOTALES,
    COUNT(DISTINCT CASE WHEN F.CANTIDAD_ATENCIONES > 0 THEN F.ID_CLIENTE END) AS CLIENTES_ATENDIDOS,
    CAST(SUM(F.MONTO_ATENCION) /
         NULLIF(COUNT(DISTINCT CASE WHEN F.CANTIDAD_ATENCIONES > 0 THEN F.ID_CLIENTE END), 0)
         AS DECIMAL(10,2)) AS KPI_03_INGRESO_PROMEDIO_CLIENTE_ATENDIDO
FROM dbo.FAC_VENTAS AS F;
GO

-- FRECUENCIA PROMEDIO DE ATENCIONES POR CLIENTE ATENDIDO
-- Equivalente conceptual: [Total Atenciones] / [Clientes Atendidos]
SELECT
    COALESCE(SUM(F.CANTIDAD_ATENCIONES), 0) AS TOTAL_ATENCIONES,
    COUNT(DISTINCT CASE WHEN F.CANTIDAD_ATENCIONES > 0 THEN F.ID_CLIENTE END) AS CLIENTES_ATENDIDOS,
    CAST(1.0 * SUM(F.CANTIDAD_ATENCIONES) /
         NULLIF(COUNT(DISTINCT CASE WHEN F.CANTIDAD_ATENCIONES > 0 THEN F.ID_CLIENTE END), 0)
         AS DECIMAL(10,2)) AS KPI_04_FRECUENCIA_PROMEDIO
FROM dbo.FAC_VENTAS AS F;
GO

-- CLIENTES INACTIVOS, COMPARABLE CON LA MEDIDA DAX
-- No incluye clientes sin ninguna atencion previa.
-- Fecha dinamica, igual que TODAY() en Power BI.
DECLARE @FECHA_CORTE_KPI08 DATE = CAST(GETDATE() AS DATE);
;WITH ULTIMA_ATENCION_KPI08 AS
(
    SELECT F.ID_CLIENTE, MAX(F.FECHA) AS ULTIMA_FECHA
    FROM dbo.FAC_VENTAS AS F
    WHERE F.CANTIDAD_ATENCIONES = 1
    GROUP BY F.ID_CLIENTE
)
SELECT
    @FECHA_CORTE_KPI08 AS FECHA_CORTE,
    COUNT(*) AS KPI_08_CLIENTES_INACTIVOS
FROM ULTIMA_ATENCION_KPI08
WHERE DATEDIFF(DAY, ULTIMA_FECHA, @FECHA_CORTE_KPI08) > 90;
GO

-- CLIENTES NUEVOS EN UN PERIODO
-- Primera atencion de cada cliente dentro del rango elegido.
-- Ajustar fechas al periodo que se desea documentar.
DECLARE @FECHA_INICIO_KPI09 DATE = '2024-10-01';
DECLARE @FECHA_FIN_KPI09 DATE = '2026-11-05';
;WITH PRIMERA_ATENCION_KPI09 AS
(
    SELECT F.ID_CLIENTE, MIN(F.FECHA) AS PRIMERA_FECHA
    FROM dbo.FAC_VENTAS AS F
    WHERE F.CANTIDAD_ATENCIONES > 0
    GROUP BY F.ID_CLIENTE
)
SELECT
    @FECHA_INICIO_KPI09 AS FECHA_INICIO,
    @FECHA_FIN_KPI09 AS FECHA_FIN,
    COUNT(*) AS KPI_09_CLIENTES_NUEVOS
FROM PRIMERA_ATENCION_KPI09
WHERE PRIMERA_FECHA >= @FECHA_INICIO_KPI09
  AND PRIMERA_FECHA <= @FECHA_FIN_KPI09;
GO

-- PROMEDIO DE DIAS ENTRE ATENCIONES
-- Para cada cliente se toma la atencion anterior con fecha estrictamente menor.
-- Equivale a la logica de la columna calculada DAX compartida.
;WITH FECHAS_ATENDIDAS_KPI10 AS
(
    SELECT F.ID_CLIENTE, F.FECHA
    FROM dbo.FAC_VENTAS AS F
    WHERE F.CANTIDAD_ATENCIONES > 0
),
INTERVALOS_KPI10 AS
(
    SELECT
        A.ID_CLIENTE,
        A.FECHA,
        (SELECT MAX(B.FECHA)
         FROM FECHAS_ATENDIDAS_KPI10 AS B
         WHERE B.ID_CLIENTE = A.ID_CLIENTE
           AND B.FECHA < A.FECHA) AS FECHA_ANTERIOR
    FROM FECHAS_ATENDIDAS_KPI10 AS A
)
SELECT
    COUNT(FECHA_ANTERIOR) AS INTERVALOS_VALIDOS,
    CAST(AVG(1.0 * DATEDIFF(DAY, FECHA_ANTERIOR, FECHA))
         AS DECIMAL(10,2)) AS KPI_10_PROMEDIO_DIAS_ENTRE_ATENCIONES
FROM INTERVALOS_KPI10
WHERE FECHA_ANTERIOR IS NOT NULL;
GO
