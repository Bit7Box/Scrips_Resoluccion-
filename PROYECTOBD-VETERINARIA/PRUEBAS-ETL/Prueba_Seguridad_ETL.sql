USE DATAMARTVETERINARIA;
GO
-- T-07: PRUEBA DE SEGURIDAD
-- CREAR UN USUARIO DE PRUEBA SIN PERMISOS
-- PARA MODIFICAR LOS DATOS DEL DATA MART.
IF NOT EXISTS (
    SELECT 1
    FROM sys.database_principals
    WHERE name = 'USUARIO_LECTURA_VET'
)
BEGIN
    CREATE USER USUARIO_LECTURA_VET
    WITHOUT LOGIN;
END
GO
-- PERMITIR CONSULTAS SOBRE LAS TABLAS DEL ESQUEMA DBO.
GRANT SELECT ON SCHEMA::dbo
TO USUARIO_LECTURA_VET;
GO
-- COMPROBAR QUE EL USUARIO EXISTE.
SELECT
    NAME AS USUARIO,
    TYPE_DESC AS TIPO_USUARIO
FROM sys.database_principals
WHERE NAME = 'USUARIO_LECTURA_VET';
GO


-- T-07: PRUEBA 1
-- VERIFICAR QUE EL USUARIO PUEDE CONSULTAR
-- LOS DATOS DEL DATA MART.

EXECUTE AS USER = 'USUARIO_LECTURA_VET';
SELECT
    COUNT(*) AS TOTAL_CLIENTES
FROM dbo.DIM_CLIENTE;
SELECT
    COUNT(*) AS TOTAL_CITAS,
    SUM(MONTO_ATENCION) AS INGRESOS_TOTALES
FROM dbo.FAC_VENTAS;
REVERT;
GO



-- T-07: PRUEBA 2
-- VERIFICAR QUE EL USUARIO NO PUEDE
-- MODIFICAR LOS REGISTROS DEL DATA MART.
EXECUTE AS USER = 'USUARIO_LECTURA_VET';
BEGIN TRY
    BEGIN TRANSACTION;
    DELETE FROM dbo.FAC_VENTAS
    WHERE 1 = 0;
    ROLLBACK TRANSACTION;
    SELECT
        'ERROR: SE PERMITIO EL DELETE'
        AS RESULTADO;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0
        ROLLBACK TRANSACTION;
    SELECT
        'ACCESO DENEGADO CORRECTAMENTE'
        AS RESULTADO,
        ERROR_NUMBER() AS CODIGO_ERROR,
        ERROR_MESSAGE() AS MENSAJE_ERROR;
END CATCH;
REVERT;
GO



USE DATAMARTVETERINARIA;
GO
-- T-07: PRUEBA 3
-- VERIFICAR QUE EL USUARIO NO TIENE
-- PERMISO PARA INSERTAR REGISTROS.
EXECUTE AS USER = 'USUARIO_LECTURA_VET';
SELECT
    'INSERT' AS OPERACION,
    HAS_PERMS_BY_NAME(
        'dbo.FAC_VENTAS',
        'OBJECT',
        'INSERT'
    ) AS TIENE_PERMISO;

-- T-07: PRUEBA 4
-- VERIFICAR QUE EL USUARIO NO TIENE
-- PERMISO PARA ACTUALIZAR REGISTROS.
SELECT
    'UPDATE' AS OPERACION,
    HAS_PERMS_BY_NAME(
        'dbo.FAC_VENTAS',
        'OBJECT',
        'UPDATE'
    ) AS TIENE_PERMISO;
REVERT;
GO
