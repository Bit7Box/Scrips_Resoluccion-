
USE DATAMARTVETERINARIA;
GO

-- CANTIDAD DE REGISTROS CARGADOS
SELECT 'STG_CLIENTE' AS TABLA, COUNT(*) AS TOTAL_REGISTROS
FROM STG_CLIENTE
UNION ALL
SELECT 'STG_UBICACION', COUNT(*)
FROM STG_UBICACION
UNION ALL
SELECT 'DIM_CLIENTE', COUNT(*)
FROM DIM_CLIENTE
UNION ALL
SELECT 'FAC_VENTAS', COUNT(*)
FROM FAC_VENTAS;
GO

-- CLIENTES CON DATOS OBLIGATORIOS FALTANTES
SELECT *
FROM STG_CLIENTE
WHERE ID_CLIENTE IS NULL
   OR NOMBRE IS NULL
   OR APELLIDO IS NULL;
GO

-- UBICACIONES CON DATOS FALTANTES
SELECT *
FROM STG_UBICACION
WHERE ID_CLIENTE IS NULL
   OR PAIS IS NULL
   OR DISTRITO IS NULL;
GO

-- CLIENTES CON UBICACIONES DUPLICADAS
SELECT ID_CLIENTE, COUNT(*) AS CANTIDAD
FROM STG_UBICACION
GROUP BY ID_CLIENTE
HAVING COUNT(*) > 1;
GO

-- CLIENTES SIN UBICACION REGISTRADA
SELECT C.ID_CLIENTE, C.NOMBRE, C.APELLIDO
FROM STG_CLIENTE C
LEFT JOIN STG_UBICACION U
    ON C.ID_CLIENTE = U.ID_CLIENTE
WHERE U.ID_CLIENTE IS NULL;
GO

-- UBICACIONES SIN CLIENTE CORRESPONDIENTE
SELECT U.*
FROM STG_UBICACION U
LEFT JOIN STG_CLIENTE C
    ON U.ID_CLIENTE = C.ID_CLIENTE
WHERE C.ID_CLIENTE IS NULL;
GO

-- ESTADO DE LOS PAGOS EN LA BASE DE ORIGEN
SELECT ESTADO,
       COUNT(*) AS CANTIDAD_PAGOS,
       SUM(MONTO) AS MONTO_TOTAL
FROM VETERINARIABD1.DBO.PAGO
GROUP BY ESTADO;
GO

-- COMPARACION DE CITAS DE ORIGEN Y HECHOS CARGADOS
SELECT
    (SELECT COUNT(*)
     FROM VETERINARIABD1.DBO.CITA) AS CITAS_ORIGEN,
    (SELECT COUNT(*)
     FROM FAC_VENTAS) AS REGISTROS_FAC_VENTAS;
GO

-- IDENTIFICAR CITAS SIN PAGO REGISTRADO
SELECT
    C.ID_CITA,
    C.FECHA_HORA,
    C.ESTADO AS ESTADO_CITA
FROM VETERINARIABD1.DBO.CITA C
LEFT JOIN VETERINARIABD1.DBO.PAGO P
    ON C.ID_CITA = P.ID_CITA
WHERE P.ID_CITA IS NULL;
GO

-- VERIFICAR LOS PAGOS Y MONTOS DE CADA CITA
SELECT
    C.ID_CITA,
    C.ESTADO AS ESTADO_CITA,
    P.ESTADO AS ESTADO_PAGO,
    P.MONTO,
    F.MONTO_ATENCION
FROM VETERINARIABD1.DBO.CITA C
LEFT JOIN VETERINARIABD1.DBO.PAGO P
    ON C.ID_CITA = P.ID_CITA
LEFT JOIN DIM_SERVICIO S
    ON S.PK_SERVICIO = C.ID_CITA
LEFT JOIN FAC_VENTAS F
    ON F.ID_SERVICIO = S.ID_SERVICIO
ORDER BY C.ID_CITA;
GO

