USE DATAMARTVETERINARIA
GO

-- COMPROBACION DE DATOS

SELECT
    COUNT(*) AS TOTAL_CITAS,
    SUM(CANTIDAD_ATENCIONES) AS TOTAL_ATENCIONES,
    SUM(MONTO_ATENCION) AS INGRESOS_TOTALES,
    COUNT(DISTINCT ID_CLIENTE) AS CLIENTES_CON_CITAS,
    COUNT(DISTINCT ID_MASCOTA) AS MASCOTAS_CON_CITAS
FROM FAC_VENTAS
GO

-- RECURRENCIA DE CLIENTES

WITH ATENCIONES_CLIENTE AS
(
    SELECT
        C.ID_CLIENTE,
        C.NOM_CLIENTE,
        C.APE_CLIENTE,
        SUM(F.CANTIDAD_ATENCIONES) AS TOTAL_ATENCIONES
    FROM DIM_CLIENTE C
    LEFT JOIN FAC_VENTAS F
        ON C.ID_CLIENTE = F.ID_CLIENTE
    GROUP BY
        C.ID_CLIENTE,
        C.NOM_CLIENTE,
        C.APE_CLIENTE
)
SELECT
    COUNT(*) AS TOTAL_CLIENTES,
    SUM(CASE WHEN TOTAL_ATENCIONES >= 2 THEN 1 ELSE 0 END)
        AS CLIENTES_RECURRENTES,
    SUM(CASE WHEN TOTAL_ATENCIONES = 1 THEN 1 ELSE 0 END)
        AS CLIENTES_UNA_ATENCION,
    SUM(CASE WHEN TOTAL_ATENCIONES = 0 THEN 1 ELSE 0 END)
        AS CLIENTES_SIN_ATENCIONES,
    CAST(
        100.0 * SUM(CASE WHEN TOTAL_ATENCIONES >= 2 THEN 1 ELSE 0 END)
        / NULLIF(COUNT(*), 0)
        AS DECIMAL(10,2)
    ) AS TASA_RECURRENCIA
FROM ATENCIONES_CLIENTE
GO


-- CLIENTES INACTIVOS (MAS DE 90 DIAS)

WITH ULTIMA_ATENCION AS
(
    SELECT
        C.ID_CLIENTE,
        C.NOM_CLIENTE,
        C.APE_CLIENTE,
        MAX(
            CASE
                WHEN F.CANTIDAD_ATENCIONES = 1 THEN F.FECHA
            END
        ) AS ULTIMA_FECHA
    FROM DIM_CLIENTE C
    LEFT JOIN FAC_VENTAS F
        ON C.ID_CLIENTE = F.ID_CLIENTE
    GROUP BY
        C.ID_CLIENTE,
        C.NOM_CLIENTE,
        C.APE_CLIENTE
)
SELECT
    ID_CLIENTE,
    NOM_CLIENTE,
    APE_CLIENTE,
    ULTIMA_FECHA,
    DATEDIFF(DAY, ULTIMA_FECHA, GETDATE()) AS DIAS_SIN_ATENCION
FROM ULTIMA_ATENCION
WHERE ULTIMA_FECHA < DATEADD(DAY, -90, CAST(GETDATE() AS DATE))
   OR ULTIMA_FECHA IS NULL
ORDER BY ULTIMA_FECHA
GO


-- FRECUENCIA DE ATENCIONES POR CLIENTE

SELECT
    C.ID_CLIENTE,
    C.NOM_CLIENTE,
    C.APE_CLIENTE,
    SUM(F.CANTIDAD_ATENCIONES) AS TOTAL_ATENCIONES,
    MIN(CASE WHEN F.CANTIDAD_ATENCIONES = 1 THEN F.FECHA END)
        AS PRIMERA_ATENCION,
    MAX(CASE WHEN F.CANTIDAD_ATENCIONES = 1 THEN F.FECHA END)
        AS ULTIMA_ATENCION
FROM DIM_CLIENTE C
LEFT JOIN FAC_VENTAS F
    ON C.ID_CLIENTE = F.ID_CLIENTE
GROUP BY
    C.ID_CLIENTE,
    C.NOM_CLIENTE,
    C.APE_CLIENTE
ORDER BY TOTAL_ATENCIONES DESC
GO


-- INGRESOS POR CLIENTE

SELECT
    C.ID_CLIENTE,
    C.NOM_CLIENTE,
    C.APE_CLIENTE,
    SUM(F.CANTIDAD_ATENCIONES) AS ATENCIONES,
    SUM(F.MONTO_ATENCION) AS INGRESOS_CLIENTE
FROM DIM_CLIENTE C
INNER JOIN FAC_VENTAS F
    ON C.ID_CLIENTE = F.ID_CLIENTE
GROUP BY
    C.ID_CLIENTE,
    C.NOM_CLIENTE,
    C.APE_CLIENTE
ORDER BY INGRESOS_CLIENTE DESC
GO


-- INDICADORES GENERALES PARA POWER BI

SELECT
    SUM(CANTIDAD_CITAS) AS TOTAL_CITAS,
    SUM(CANTIDAD_ATENCIONES) AS TOTAL_ATENCIONES,
    SUM(MONTO_ATENCION) AS INGRESOS_TOTALES,

    CAST(
        100.0 * SUM(CANTIDAD_ATENCIONES)
        / NULLIF(SUM(CANTIDAD_CITAS), 0)
        AS DECIMAL(10,2)
    ) AS PORCENTAJE_ATENCION,

    CAST(
        SUM(MONTO_ATENCION)
        / NULLIF(SUM(CANTIDAD_ATENCIONES), 0)
        AS DECIMAL(10,2)
    ) AS INGRESO_PROMEDIO_POR_ATENCION
FROM FAC_VENTAS
GO