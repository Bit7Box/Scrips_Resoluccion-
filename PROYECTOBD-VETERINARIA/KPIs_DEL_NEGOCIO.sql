-- KPI GENERALES DEL DATA MART
USE DATAMARTVETERINARIA;
GO

SELECT
    COALESCE(SUM(CANTIDAD_CITAS), 0) AS TOTAL_CITAS,
    COALESCE(SUM(CANTIDAD_ATENCIONES), 0) AS TOTAL_ATENCIONES,
    COALESCE(SUM(MONTO_ATENCION), 0) AS INGRESOS_TOTALES,
    COUNT(DISTINCT ID_CLIENTE) AS CLIENTES_CON_CITAS,
    COUNT(DISTINCT ID_MASCOTA) AS MASCOTAS_CON_CITAS,
    COUNT(DISTINCT CASE WHEN CANTIDAD_ATENCIONES > 0 THEN ID_CLIENTE END)
        AS CLIENTES_ATENDIDOS,
    COUNT(DISTINCT CASE WHEN CANTIDAD_ATENCIONES > 0 THEN ID_MASCOTA END)
        AS MASCOTAS_ATENDIDAS,
    CAST(100.0 * SUM(CANTIDAD_ATENCIONES) /
        NULLIF(SUM(CANTIDAD_CITAS), 0) AS DECIMAL(10,2))
        AS PORCENTAJE_ATENCION,
    CAST(SUM(MONTO_ATENCION) /
        NULLIF(SUM(CANTIDAD_ATENCIONES), 0) AS DECIMAL(10,2))
        AS INGRESO_PROMEDIO_POR_ATENCION
FROM dbo.FAC_VENTAS;
GO

-- RECURRENCIA DE CLIENTES
-- Recurrente: cliente con al menos dos atenciones realizada
-- Denominador: todos los clientes registrados en DIM_CLIENTE
WITH ATENCIONES_CLIENTE AS
(
    SELECT
        C.ID_CLIENTE,
        COALESCE(SUM(F.CANTIDAD_ATENCIONES), 0) AS TOTAL_ATENCIONES
    FROM dbo.DIM_CLIENTE AS C
    LEFT JOIN dbo.FAC_VENTAS AS F
        ON C.ID_CLIENTE = F.ID_CLIENTE
    GROUP BY C.ID_CLIENTE
)
SELECT
    COUNT(*) AS TOTAL_CLIENTES,
    COALESCE(SUM(CASE WHEN TOTAL_ATENCIONES >= 2 THEN 1 ELSE 0 END), 0)
        AS CLIENTES_RECURRENTES,
    COALESCE(SUM(CASE WHEN TOTAL_ATENCIONES = 1 THEN 1 ELSE 0 END), 0)
        AS CLIENTES_UNA_ATENCION,
    COALESCE(SUM(CASE WHEN TOTAL_ATENCIONES = 0 THEN 1 ELSE 0 END), 0)
        AS CLIENTES_SIN_ATENCIONES,
    CAST(100.0 * SUM(CASE WHEN TOTAL_ATENCIONES >= 2 THEN 1 ELSE 0 END) /
        NULLIF(COUNT(*), 0) AS DECIMAL(10,2)) AS TASA_RECURRENCIA_PCT
FROM ATENCIONES_CLIENTE;
GO

-- CLIENTES INACTIVOS POR MAS DE 90 DIAS
-- Incluye clientes que nunca registraron una atencion
WITH ULTIMA_ATENCION AS
(
    SELECT
        C.ID_CLIENTE,
        C.NOM_CLIENTE,
        C.APE_CLIENTE,
        MAX(CASE WHEN F.CANTIDAD_ATENCIONES > 0 THEN F.FECHA END)
            AS ULTIMA_FECHA
    FROM dbo.DIM_CLIENTE AS C
    LEFT JOIN dbo.FAC_VENTAS AS F
        ON C.ID_CLIENTE = F.ID_CLIENTE
    GROUP BY C.ID_CLIENTE, C.NOM_CLIENTE, C.APE_CLIENTE
)
SELECT
    ID_CLIENTE,
    NOM_CLIENTE,
    APE_CLIENTE,
    ULTIMA_FECHA,
    DATEDIFF(DAY, ULTIMA_FECHA, CAST(GETDATE() AS DATE))
        AS DIAS_SIN_ATENCION,
    CASE WHEN ULTIMA_FECHA IS NULL THEN 'SIN ATENCIONES'
         ELSE 'INACTIVO MAS DE 90 DIAS' END AS ESTADO_INACTIVIDAD
FROM ULTIMA_ATENCION
WHERE ULTIMA_FECHA < DATEADD(DAY, -90, CAST(GETDATE() AS DATE))
   OR ULTIMA_FECHA IS NULL
ORDER BY ULTIMA_FECHA, ID_CLIENTE;
GO

-- FRECUENCIA DE ATENCIONES POR CLIENTE
SELECT
    C.ID_CLIENTE,
    C.NOM_CLIENTE,
    C.APE_CLIENTE,
    COALESCE(SUM(F.CANTIDAD_ATENCIONES), 0) AS TOTAL_ATENCIONES,
    MIN(CASE WHEN F.CANTIDAD_ATENCIONES > 0 THEN F.FECHA END)
        AS PRIMERA_ATENCION,
    MAX(CASE WHEN F.CANTIDAD_ATENCIONES > 0 THEN F.FECHA END)
        AS ULTIMA_ATENCION
FROM dbo.DIM_CLIENTE AS C
LEFT JOIN dbo.FAC_VENTAS AS F
    ON C.ID_CLIENTE = F.ID_CLIENTE
GROUP BY C.ID_CLIENTE, C.NOM_CLIENTE, C.APE_CLIENTE
ORDER BY TOTAL_ATENCIONES DESC, C.ID_CLIENTE;
GO

-- INGRESOS Y ATENCIONES POR CLIENTE
SELECT
    C.ID_CLIENTE,
    C.NOM_CLIENTE,
    C.APE_CLIENTE,
    COALESCE(SUM(F.CANTIDAD_ATENCIONES), 0) AS ATENCIONES,
    COALESCE(SUM(F.MONTO_ATENCION), 0) AS INGRESOS_CLIENTE,
    CAST(SUM(F.MONTO_ATENCION) /
        NULLIF(SUM(F.CANTIDAD_ATENCIONES), 0) AS DECIMAL(10,2))
        AS INGRESO_PROMEDIO_POR_ATENCION
FROM dbo.DIM_CLIENTE AS C
LEFT JOIN dbo.FAC_VENTAS AS F
    ON C.ID_CLIENTE = F.ID_CLIENTE
GROUP BY C.ID_CLIENTE, C.NOM_CLIENTE, C.APE_CLIENTE
ORDER BY INGRESOS_CLIENTE DESC, C.ID_CLIENTE;
GO

-- INDICADORES POR VETERINARIO
SELECT
    V.ID_VETERINARIO,
    V.NOM_VETERINARIO,
    V.APE_VETERINARIO,
    V.ESPECIALIDAD_VETERINARIO,
    COALESCE(SUM(F.CANTIDAD_CITAS), 0) AS TOTAL_CITAS,
    COALESCE(SUM(F.CANTIDAD_ATENCIONES), 0) AS TOTAL_ATENCIONES,
    COALESCE(SUM(F.MONTO_ATENCION), 0) AS INGRESOS_GENERADOS,
    CAST(100.0 * SUM(F.CANTIDAD_ATENCIONES) /
        NULLIF(SUM(F.CANTIDAD_CITAS), 0) AS DECIMAL(10,2))
        AS PORCENTAJE_ATENCION
FROM dbo.DIM_VETERINARIO AS V
LEFT JOIN dbo.FAC_VENTAS AS F
    ON V.ID_VETERINARIO = F.ID_VETERINARIO
GROUP BY V.ID_VETERINARIO, V.NOM_VETERINARIO,
         V.APE_VETERINARIO, V.ESPECIALIDAD_VETERINARIO
ORDER BY TOTAL_ATENCIONES DESC, V.ID_VETERINARIO;
GO

-- EVOLUCION MENSUAL DE CITAS, ATENCIONES E INGRESOS
SELECT
    D.AÑO AS ANIO,
    D.MES,
    COALESCE(SUM(F.CANTIDAD_CITAS), 0) AS TOTAL_CITAS,
    COALESCE(SUM(F.CANTIDAD_ATENCIONES), 0) AS TOTAL_ATENCIONES,
    COALESCE(SUM(F.MONTO_ATENCION), 0) AS INGRESOS_TOTALES
FROM dbo.DIM_FECHA AS D
INNER JOIN dbo.FAC_VENTAS AS F
    ON D.FECHA = F.FECHA
GROUP BY D.AÑO, D.MES
ORDER BY D.AÑO, D.MES;
GO

-- INDICADORES POR ESPECIE
SELECT
    M.ESPECIE_MASCOTA,
    COUNT(DISTINCT M.ID_MASCOTA) AS MASCOTAS_CON_CITAS,
    COALESCE(SUM(F.CANTIDAD_CITAS), 0) AS TOTAL_CITAS,
    COALESCE(SUM(F.CANTIDAD_ATENCIONES), 0) AS TOTAL_ATENCIONES,
    COALESCE(SUM(F.MONTO_ATENCION), 0) AS INGRESOS_TOTALES
FROM dbo.FAC_VENTAS AS F
INNER JOIN dbo.DIM_MASCOTA AS M
    ON F.ID_MASCOTA = M.ID_MASCOTA
GROUP BY M.ESPECIE_MASCOTA
ORDER BY TOTAL_ATENCIONES DESC, M.ESPECIE_MASCOTA;
GO

-- VALIDACION CRUZADA: ORIGEN VS. DATA MART
-- Si todas las diferencias son 0, los totales coinciden
-- No reemplaza los controles de calidad detallados del ETL
SELECT
    (SELECT COUNT(*) FROM VeterinariaBD1.dbo.CITA)
        AS CITAS_ORIGEN,
    (SELECT COALESCE(SUM(CANTIDAD_CITAS), 0) FROM dbo.FAC_VENTAS)
        AS CITAS_DATAMART,
    (SELECT COUNT(*) FROM VeterinariaBD1.dbo.CITA
        WHERE ESTADO = 'Atendida') AS ATENCIONES_ORIGEN,
    (SELECT COALESCE(SUM(CANTIDAD_ATENCIONES), 0) FROM dbo.FAC_VENTAS)
        AS ATENCIONES_DATAMART,
    (SELECT COALESCE(SUM(MONTO), 0) FROM VeterinariaBD1.dbo.PAGO
        WHERE ESTADO = 'Pagado') AS INGRESOS_ORIGEN,
    (SELECT COALESCE(SUM(MONTO_ATENCION), 0) FROM dbo.FAC_VENTAS)
        AS INGRESOS_DATAMART;
GO

