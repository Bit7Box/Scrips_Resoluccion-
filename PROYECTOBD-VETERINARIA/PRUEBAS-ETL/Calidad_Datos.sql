USE DATAMARTVETERINARIA;
GO

DECLARE @PRUEBA INT = 1;
DECLARE @INICIO DATETIME2(7);
DECLARE @FIN DATETIME2(7);

DECLARE @RESULTADOS TABLE (
    PRUEBA INT,
    TIEMPO_MS BIGINT
);

WHILE @PRUEBA <= 5
BEGIN
    SET @INICIO = SYSDATETIME();

    EXEC dbo.USP_ETL_DATAMARTVETERINARIA1;

    SET @FIN = SYSDATETIME();

    INSERT INTO @RESULTADOS
    VALUES (
        @PRUEBA,
        DATEDIFF_BIG(MILLISECOND, @INICIO, @FIN)
    );

    SET @PRUEBA = @PRUEBA + 1;
END;

SELECT
    PRUEBA,
    TIEMPO_MS,
    TIEMPO_MS / 1000.0 AS TIEMPO_SEGUNDOS
FROM @RESULTADOS
ORDER BY PRUEBA;

SELECT
    COUNT(*) AS TOTAL_PRUEBAS,
    AVG(CAST(TIEMPO_MS AS DECIMAL(18,2))) AS PROMEDIO_MS,
    MIN(TIEMPO_MS) AS MINIMO_MS,
    MAX(TIEMPO_MS) AS MAXIMO_MS
FROM @RESULTADOS;
GO


