-- DIMENSION CLIENTE
-- ORIGEN DE DATOS: CLIENTE + TXT DE UBICACION
-- JERARQUIA: PAIS -- DISTRITO -- CLIENTE
--
-- ANALISIS DE KPIs:
-- Tasa de clientes recurrentes
-- Clientes con baja recurrencia
-- Clientes inactivos
-- Frecuencia promedio de atencion
-- Clientes nuevos
-- Ingresos promedio por cliente
CREATE TABLE DIM_CLIENTE
(
    -- PK: CLAVE PRIMARIA
    ID_CLIENTE INT PRIMARY KEY IDENTITY,

    -- CLAVE DEL CLIENTE EN LA BD OLTP
    PK_CLIENTE INT,

    NOM_CLIENTE VARCHAR(100),
    APE_CLIENTE VARCHAR(100),
    PAIS_CLIENTE VARCHAR(50),
    DISTRITO_CLIENTE VARCHAR(100),
    TELEFONO_CLIENTE VARCHAR(15),
    EMAIL_CLIENTE VARCHAR(100)
)
GO


-- DIMENSION MASCOTA
-- ORIGEN DE DATOS: MASCOTA
-- JERARQUIA: ESPECIE -- RAZA -- MASCOTA
--
-- ANALISIS DE KPIs:
-- Cantidad de mascotas atendidas
CREATE TABLE DIM_MASCOTA
(
    -- PK: CLAVE PRIMARIA
    ID_MASCOTA INT PRIMARY KEY IDENTITY,

    -- CLAVE DE LA MASCOTA EN LA BD OLTP
    PK_MASCOTA INT,

    NOM_MASCOTA VARCHAR(100),
    ESPECIE_MASCOTA VARCHAR(50),
    RAZA_MASCOTA VARCHAR(100),
    SEXO_MASCOTA VARCHAR(10)
)
GO


-- DIMENSION VETERINARIO
-- ORIGEN DE DATOS: VETERINARIO
-- JERARQUIA: ESPECIALIDAD -- VETERINARIO
--
-- ANALISIS  DE KPIs:
-- Frecuencia promedio de atencion
-- Ingresos promedio por cliente
-- Ticket promedio por atencion
CREATE TABLE DIM_VETERINARIO
(
    -- PK: CLAVE PRIMARIA
    ID_VETERINARIO INT PRIMARY KEY IDENTITY,

    -- CLAVE DEL VETERINARIO EN LA BD OLTP
    PK_VETERINARIO INT,

    NOM_VETERINARIO VARCHAR(100),
    APE_VETERINARIO VARCHAR(100),
    ESPECIALIDAD_VETERINARIO VARCHAR(100)
)
GO


-- DIMENSION SERVICIO
-- ORIGEN DE DATOS: CITA
-- JERARQUIA: TIPO_SERVICIO -- MOTIVO_CITA
--
-- ANALISIS DE KPIs:
-- Tasa de citas atendidas
-- Frecuencia promedio de atencion
CREATE TABLE DIM_SERVICIO
(
    -- PK: CLAVE PRIMARIA
    ID_SERVICIO INT PRIMARY KEY IDENTITY,

    -- CLAVE DEL SERVICIO
    PK_SERVICIO INT,

    TIPO_SERVICIO VARCHAR(100),
    MOTIVO_CITA VARCHAR(255)
)
GO


-- DIMENSION FECHA
-- ORIGEN: FECHA_HORA DE CITA
-- JERARQUIA: AÑO -- TRIMESTRE -- MES -- DIA
--
-- ANALISIS DE KPIs:
-- Clientes inactivos
-- Frecuencia promedio de atencion
-- Promedio de dias entre atenciones
-- Clientes nuevos
-- Ingresos promedio por cliente
-- Ticket promedio por atencion
-- Tasa de citas atendidas
CREATE TABLE DIM_FECHA
(
    -- PK: CLAVE PRIMARIA
    FECHA DATE PRIMARY KEY,

    AÑO SMALLINT,
    TRIMESTRE SMALLINT,
    MES SMALLINT,
    DIA_MES SMALLINT,
    DIA_SEMANA VARCHAR(15)
)
GO


-- STAGING CLIENTE
-- ORIGEN DE DATOS: CLIENTE
-- SE UTILIZA PARA COMPLEMENTAR LOS DATOS
-- CON EL ARCHIVO TXT DE UBICACION
CREATE TABLE STG_CLIENTE
(
    -- PK: CLAVE PRIMARIA
    ID_CLIENTE INT PRIMARY KEY,

    NOMBRE VARCHAR(100),
    APELLIDO VARCHAR(100),
    TELEFONO VARCHAR(15),
    EMAIL VARCHAR(100)
)
GO


-- STAGING UBICACION
-- ORIGEN DE DATOS: ARCHIVO TXT DE UBICACION
CREATE TABLE STG_UBICACION
(
    -- PK: CLAVE PRIMARIA
    ID_CLIENTE INT PRIMARY KEY,

    PAIS VARCHAR(50),
    DISTRITO VARCHAR(100)
)
GO


-- TABLA DE HECHOS FAC_VENTAS
-- ORIGEN DE DATOS: CITA + PAGO
-- GRANO: UNA FILA REPRESENTA UNA CITA
--
-- ANALISIS de KPIs:
-- Tasa de clientes recurrentes
-- Clientes con baja recurrencia
-- Clientes inactivos
-- Frecuencia promedio de atencion
-- Promedio de dias entre atenciones
-- Clientes nuevos
-- Ingresos promedio por cliente
-- Ticket promedio por atencion
-- Tasa de citas atendidas
CREATE TABLE FAC_VENTAS
(
    -- PK: CLAVE PRIMARIA
    ID_VENTA INT PRIMARY KEY IDENTITY,

    -- FK: DIMENSION CLIENTE
    ID_CLIENTE INT REFERENCES DIM_CLIENTE(ID_CLIENTE),

    -- FK: DIMENSION MASCOTA
    ID_MASCOTA INT REFERENCES DIM_MASCOTA(ID_MASCOTA),

    -- FK: DIMENSION VETERINARIO
    ID_VETERINARIO INT REFERENCES DIM_VETERINARIO(ID_VETERINARIO),

    -- FK: DIMENSION SERVICIO
    ID_SERVICIO INT REFERENCES DIM_SERVICIO(ID_SERVICIO),

    -- FK: DIMENSION FECHA
    FECHA DATE REFERENCES DIM_FECHA(FECHA),

    -- MEDIDAS
    CANTIDAD_ATENCIONES INT,
    MONTO_ATENCION DECIMAL(10,2),
    CANTIDAD_CITAS INT,
    CANTIDAD_MASCOTAS INT
)
GO


-- RELACION ENTRE DIMENSIONES, MEDIDAS Y KPIs

-- DIM_CLIENTE + DIM_FECHA   
-- RECURRENCIA / INACTIVIDAD / CLIENTES NUEVOS


-- DIM_CLIENTE + MONTO_ATENCION
-- INGRESOS PROMEDIO / TICKET PROMEDIO


-- DIM_FECHA + CANTIDAD_ATENCIONES
-- FRECUENCIA / DIAS ENTRE ATENCIONES


-- DIM_SERVICIO + CANTIDAD_CITAS
-- ANALISIS DE SERVICIOS


-- CANTIDAD_ATENCIONES + CANTIDAD_CITAS
-- TASA DE CITAS ATENDIDAS