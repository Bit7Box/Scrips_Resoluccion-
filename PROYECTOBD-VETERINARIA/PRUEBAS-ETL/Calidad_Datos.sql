-- IDENTIFICAR CLIENTES CON DATOS OBLIGATORIOS NULOS
-- Busca registros de clientes que no tengan identificador,
-- nombre o apellido.
-- Si no devuelve filas, no existen valores NULL en estos campos.
-- Esta consulta no detecta cadenas vacias ni espacios en blanco.
SELECT *
FROM STG_CLIENTE
WHERE ID_CLIENTE IS NULL
   OR NOMBRE IS NULL
   OR APELLIDO IS NULL;
GO

-- IDENTIFICAR UBICACIONES CON DATOS OBLIGATORIOS NULOS
-- Busca registros de ubicaciones sin identificador de cliente,
-- pais o distrito.
-- Si no devuelve filas, los campos evaluados no contienen NULL.
-- Esta consulta no detecta cadenas vacias ni espacios en blanco.
SELECT *
FROM STG_UBICACION
WHERE ID_CLIENTE IS NULL
   OR PAIS IS NULL
   OR DISTRITO IS NULL;
GO

-- DETECTAR UBICACIONES DUPLICADAS POR CLIENTE
-- Agrupa las ubicaciones por identificador de cliente.
-- Muestra aquellos clientes que tienen mas de un registro
-- en la tabla STG_UBICACION.
-- Si no devuelve filas, no se encontraron identificadores repetidos.
SELECT ID_CLIENTE, COUNT(*) AS CANTIDAD
FROM STG_UBICACION
GROUP BY ID_CLIENTE
HAVING COUNT(*) > 1;
GO

-- IDENTIFICAR CLIENTES SIN UBICACION REGISTRADA
-- Compara los clientes de staging con sus ubicaciones.
-- Muestra los clientes que no tienen un registro correspondiente
-- en STG_UBICACION.
-- Si no devuelve filas, todos los clientes tienen una ubicacion asociada.
SELECT C.ID_CLIENTE, C.NOMBRE, C.APELLIDO
FROM STG_CLIENTE C
LEFT JOIN STG_UBICACION U
    ON C.ID_CLIENTE = U.ID_CLIENTE
WHERE U.ID_CLIENTE IS NULL;
GO

-- IDENTIFICAR UBICACIONES SIN CLIENTE CORRESPONDIENTE
-- Busca registros de ubicaciones cuyo identificador de cliente
-- no existe en STG_CLIENTE.
-- Permite detectar registros huerfanos en los datos de staging.
-- Si no devuelve filas, no se encontraron ubicaciones sin cliente.
SELECT U.*
FROM STG_UBICACION U
LEFT JOIN STG_CLIENTE C
    ON U.ID_CLIENTE = C.ID_CLIENTE
WHERE C.ID_CLIENTE IS NULL;
GO

-- CONSULTAR EL ESTADO Y MONTO DE LOS PAGOS DEL ORIGEN
-- Agrupa los pagos de VeterinariaBD1 segun su estado.
-- Muestra cuantos pagos existen por estado y la suma de sus montos.
-- Permite distinguir pagos registrados como Pagado o Pendiente.
-- No representa necesariamente los ingresos efectivamente cobrados,
-- porque incluye los montos de todos los estados.
SELECT ESTADO,
       COUNT(*) AS CANTIDAD_PAGOS,
       SUM(MONTO) AS MONTO_TOTAL
FROM VETERINARIABD1.DBO.PAGO
GROUP BY ESTADO;
GO

-- COMPARAR LAS CITAS DEL ORIGEN CON LA TABLA DE HECHOS
-- Obtiene la cantidad de citas registradas en VeterinariaBD1
-- y la cantidad de filas cargadas en FAC_VENTAS.
-- Ambos valores deben coincidir porque cada fila de FAC_VENTAS
-- representa una cita.
-- Una coincidencia de cantidades no garantiza por si sola
-- que todos los datos de las citas sean correctos.
SELECT
    (SELECT COUNT(*)
     FROM VETERINARIABD1.DBO.CITA) AS CITAS_ORIGEN,
    (SELECT COUNT(*)
     FROM FAC_VENTAS) AS REGISTROS_FAC_VENTAS;
GO

-- IDENTIFICAR CITAS QUE NO TIENEN UN PAGO REGISTRADO
-- Compara las citas con la tabla PAGO de VeterinariaBD1.
-- Muestra el identificador, fecha y estado de las citas
-- que no tienen un registro de pago asociado.
-- Una cita sin pago no necesariamente representa un error:
-- puede estar pendiente de atencion o de cobro.
SELECT
    C.ID_CITA,
    C.FECHA_HORA,
    C.ESTADO AS ESTADO_CITA
FROM VETERINARIABD1.DBO.CITA C
LEFT JOIN VETERINARIABD1.DBO.PAGO P
    ON C.ID_CITA = P.ID_CITA
WHERE P.ID_CITA IS NULL;
GO

-- VERIFICAR LOS MONTOS DE LAS CITAS ENTRE ORIGEN Y DATA MART
-- Relaciona las citas y pagos de VeterinariaBD1 con FAC_VENTAS,
-- utilizando DIM_SERVICIO como enlace mediante el ID de la cita.
-- Muestra el estado de la cita, el estado del pago,
-- el monto registrado en origen y el monto cargado en el Data Mart.
-- Permite revisar si los pagos realizados se reflejan correctamente
-- en MONTO_ATENCION.
-- Los pagos pendientes o inexistentes pueden generar un monto
-- de atencion igual a cero segun las reglas del ETL.
-- Esta relacion supone que DIM_SERVICIO.PK_SERVICIO
-- corresponde al identificador de cada cita.
SELECT
    C.ID_CITA,
    C.ESTADO AS ESTADO_CITA,
    P.ESTADO AS ESTADO_PAGO,
    P.MONTO,
    F.MONTO_ATENCION
FROM VETERINARIABD1.DBO.CITA C
LEFT JOIN VETERINARIABD1.DBO.PAGO P
    ON C.ID_CITA = P.ID_CITA
LEFT JOIN DIM_SERVICIO S
    ON S.PK_SERVICIO = C.ID_CITA
LEFT JOIN FAC_VENTAS F
    ON F.ID_SERVICIO = S.ID_SERVICIO
ORDER BY C.ID_CITA;
GO

